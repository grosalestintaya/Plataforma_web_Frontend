export function getModule(moduleKey) {
  return ACTIVITY_CATALOG?.[moduleKey] || null;
}

export function getModuleMeta(moduleKey) {
  return ACTIVITY_CATALOG?.[moduleKey]?.meta || null;
}

export function getModuleTitle(moduleKey) {
  return ACTIVITY_CATALOG?.[moduleKey]?.meta?.moduleTitle || "";
}

export function getModuleColor(moduleKey) {
  return ACTIVITY_CATALOG?.[moduleKey]?.meta?.moduleColor || "";
}

export function getActivity(moduleKey, activityType) {
  return ACTIVITY_CATALOG?.[moduleKey]?.[activityType] || null;
}

export function getActivityTitle(moduleKey, activityType) {
  return ACTIVITY_CATALOG?.[moduleKey]?.[activityType]?.title || "";
}

export function getLearnFor(moduleKey, activityType) {
  return getActivity(moduleKey, activityType);
}
